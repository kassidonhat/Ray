--====================================================================================================================================================================================================
--  This Spawns in the area VFX
--====================================================================================================================================================================================================




--====================================================================================================================================================================================================
--  Imports
--====================================================================================================================================================================================================
local world = require('openmw.world')
local core = require('openmw.core')
local types = require('openmw.types')
local util = require('openmw.util')




--====================================
-- Variables
--====================================
local AreaModel = nil
local ParticleForVFX = nil
local SpellID = nil
local SizeOfArea = nil








--====================================
-- Spawn Area VFX Logic
--====================================
local function SpawnSpellAreaLocal(sentData)
	--This spawns the area effect, an explosion in the case of the fire ray spell

	world.vfx.spawn(sentData.AreaModel,sentData.ImpactVFXPostion,{ useAmbientLight = true,
																		scale =sentData.SizeOfArea*2 ,
																		particleTextureOverride = sentData.ParticleForVFX})
end




--====================================================================================================================================================================================================
--  Event Handlers
--====================================================================================================================================================================================================
return {
	
    eventHandlers = {
		SpawnSpellArea = SpawnSpellAreaLocal
    }
	
}

